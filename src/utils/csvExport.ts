import { HydraulicResults, ProjectMetadata, PumpModel, UnitSystem, FittingItem } from '../types';
import { getPipeOdFromNps, getPipeWallThk } from './hydraulics';

interface CsvExportParams {
  results: HydraulicResults;
  project: ProjectMetadata;
  pump: PumpModel;
  arrangementName: string;
  unitSystem: UnitSystem;
  fittings?: FittingItem[];
}

function escapeCsvCell(val: string | number | boolean | null | undefined): string {
  if (val === null || val === undefined) return '';
  const str = String(val);
  if (str.includes(',') || str.includes('"') || str.includes('\n') || str.includes('\r')) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return str;
}

function row(...cells: (string | number | boolean | null | undefined)[]): string {
  return cells.map(escapeCsvCell).join(',') + '\r\n';
}

export function generateHydraulicCsvString(params: CsvExportParams): string {
  const { results, project, pump, arrangementName, fittings = [] } = params;

  let csv = '\uFEFF'; // UTF-8 BOM for Microsoft Excel

  // Header Banner
  csv += row('ASME B31.3 DIESEL PIPING HYDRAULIC SIZING & PUMP SELECTION REPORT');
  csv += row('Generated by Diesel Piping & Pump Workstation', 'Date & Time', new Date().toISOString());
  csv += row();

  // 1. Project Metadata
  csv += row('=== PROJECT & FACILITY INFORMATION ===');
  csv += row('Project Name', project.projectName || '');
  csv += row('Project Number', project.projectNumber || '');
  csv += row('Client / Operator', project.client || '');
  csv += row('Facility Location', project.location || '');
  csv += row('Lead Piping Engineer', project.leadEngineer || '');
  csv += row('Reviewer / Approver', project.reviewer || '');
  csv += row('Revision', project.revision || '');
  csv += row('Calculation Date', project.date || '');
  csv += row('Tank & Piping Arrangement', arrangementName);
  csv += row('Governing Codes', 'ASME B31.3 Process Piping / API RP 2003 / NFPA 30 / NFPA 110');
  csv += row('Engineering Scope / Notes', project.notes || '');
  csv += row();

  // 2. Fluid Operating Properties
  const fluid = results.fluid;
  csv += row('=== FLUID PHYSICAL & THERMODYNAMIC PROPERTIES ===');
  csv += row('Property', 'Value (SI Units)', 'Value (Imperial Units)', 'Standard Reference');
  csv += row('Fluid Type', fluid.type, fluid.type, 'ASTM D975 / EN 590 Ultra-Low Sulfur Diesel');
  csv += row(
    'Operating Temperature',
    `${fluid.tempC.toFixed(1)} °C`,
    `${(fluid.tempC * 1.8 + 32).toFixed(1)} °F`,
    'Design operating temperature'
  );
  csv += row(
    'Fuel Density',
    `${fluid.computedDensityKgM3.toFixed(2)} kg/m³`,
    `${(fluid.computedDensityKgM3 * 0.062428).toFixed(2)} lb/ft³`,
    'Temperature compensated ASTM D1298'
  );
  csv += row(
    'Kinematic Viscosity',
    `${fluid.computedViscosityCSt.toFixed(2)} cSt (mm²/s)`,
    `${(fluid.computedViscosityCSt * 1.07639e-5).toExponential(3)} ft²/s`,
    'Kinematic viscosity ASTM D445'
  );
  csv += row(
    'Dynamic Viscosity',
    `${(fluid.dynamicViscosityPaS * 1000).toFixed(3)} cP (mPa·s)`,
    `${(fluid.dynamicViscosityPaS * 0.67197).toExponential(3)} lb/(ft·s)`,
    'Absolute dynamic viscosity'
  );
  csv += row(
    'Vapor Pressure',
    `${fluid.vaporPressureKPa.toFixed(3)} kPa (abs)`,
    `${(fluid.vaporPressureKPa * 0.145038).toFixed(3)} psia`,
    'Reid Vapor Pressure ASTM D323'
  );
  csv += row(
    'Atmospheric Pressure',
    `${results.atmosphericPressureKPa.toFixed(2)} kPa (abs)`,
    `${(results.atmosphericPressureKPa * 0.145038).toFixed(2)} psia`,
    'Standard atmospheric sea level datum'
  );
  csv += row();

  // 3. Design Flow Demand
  csv += row('=== DESIGN FLOW DEMAND ===');
  csv += row('Parameter', 'SI Units', 'Imperial Units');
  csv += row(
    'Volumetric Flow Rate',
    `${results.flowRateM3h.toFixed(2)} m³/h (${(results.flowRateM3h * 16.6667).toFixed(1)} L/min)`,
    `${(results.flowRateM3h * 4.40287).toFixed(2)} US GPM`
  );
  csv += row(
    'Mass Flow Rate',
    `${((results.flowRateM3h * fluid.computedDensityKgM3) / 1000).toFixed(3)} tonnes/h (${((results.flowRateM3h * fluid.computedDensityKgM3) / 3600).toFixed(3)} kg/s)`,
    `${((results.flowRateM3h * fluid.computedDensityKgM3 * 2.20462) / 3600).toFixed(2)} lb/s`
  );
  csv += row();

  // 4. Suction Piping Hydraulic Analysis
  const suctionOdMm = getPipeOdFromNps(results.suctionNps);
  const suctionWallMm = getPipeWallThk(results.suctionNps, results.suctionSchedule);

  csv += row('=== SUCTION PIPING HYDRAULIC ANALYSIS (DARCY-WEISBACH) ===');
  csv += row('Parameter', 'SI Metric', 'Imperial Unit', 'ASME B31.3 / API Criterion');
  csv += row('Nominal Pipe Size & Schedule', `NPS ${results.suctionNps} / Sch ${results.suctionSchedule}`, `NPS ${results.suctionNps} / Sch ${results.suctionSchedule}`, 'ASME B36.10M Standard');
  csv += row('Outer Diameter (OD)', `${suctionOdMm.toFixed(2)} mm`, `${(suctionOdMm / 25.4).toFixed(3)} in`, 'Nominal outside diameter');
  csv += row('Inner Diameter (ID)', `${results.suctionIdMm.toFixed(2)} mm`, `${(results.suctionIdMm / 25.4).toFixed(3)} in`, 'Flow bore area');
  csv += row('Wall Thickness (t)', `${suctionWallMm.toFixed(2)} mm`, `${(suctionWallMm / 25.4).toFixed(3)} in`, 'Minimum nominal wall');
  csv += row(
    'Flow Velocity',
    `${results.suctionVelocityMps.toFixed(2)} m/s`,
    `${(results.suctionVelocityMps * 3.28084).toFixed(2)} ft/s`,
    'Suction limit: 0.6 - 1.2 m/s (ASME / API RP 2003)'
  );
  csv += row(
    'Velocity Head (v²/2g)',
    `${(Math.pow(results.suctionVelocityMps, 2) / 19.62).toFixed(3)} m`,
    `${((Math.pow(results.suctionVelocityMps * 3.28084, 2)) / 64.348).toFixed(3)} ft`,
    ''
  );
  csv += row('Reynolds Number (Re)', Math.round(results.suctionReynolds).toString(), Math.round(results.suctionReynolds).toString(), `Flow Regime: ${results.suctionRegime}`);
  csv += row('Darcy Friction Factor (f)', results.suctionFrictionFactor.toFixed(5), results.suctionFrictionFactor.toFixed(5), 'Colebrook-White Implicit Solution');
  csv += row('Major Pipe Friction Loss', `${results.suctionPipeHeadLossM.toFixed(3)} m`, `${(results.suctionPipeHeadLossM * 3.28084).toFixed(3)} ft`, 'Darcy-Weisbach head loss');
  csv += row('Minor Fittings Head Loss', `${results.suctionFittingsHeadLossM.toFixed(3)} m`, `${(results.suctionFittingsHeadLossM * 3.28084).toFixed(3)} ft`, 'Crane TP-410 ΣK·v²/2g');
  csv += row('Total Suction Head Loss', `${results.suctionTotalHeadLossM.toFixed(3)} m`, `${(results.suctionTotalHeadLossM * 3.28084).toFixed(3)} ft`, `${results.suctionPressureDropKpa.toFixed(2)} kPa / ${(results.suctionPressureDropKpa * 0.145038).toFixed(2)} psi`);
  csv += row('Pipe MAWP at Design Temp', `${results.suctionMawpBar.toFixed(1)} bar`, `${(results.suctionMawpBar * 14.5038).toFixed(1)} psi`, 'ASME B31.3 Eq. 3a pressure containment');
  csv += row();

  // 5. Discharge Piping Hydraulic Analysis
  const dischargeOdMm = getPipeOdFromNps(results.dischargeNps);
  const dischargeWallMm = getPipeWallThk(results.dischargeNps, results.dischargeSchedule);

  csv += row('=== DISCHARGE PIPING HYDRAULIC ANALYSIS (DARCY-WEISBACH) ===');
  csv += row('Parameter', 'SI Metric', 'Imperial Unit', 'ASME B31.3 / API Criterion');
  csv += row('Nominal Pipe Size & Schedule', `NPS ${results.dischargeNps} / Sch ${results.dischargeSchedule}`, `NPS ${results.dischargeNps} / Sch ${results.dischargeSchedule}`, 'ASME B36.10M Standard');
  csv += row('Outer Diameter (OD)', `${dischargeOdMm.toFixed(2)} mm`, `${(dischargeOdMm / 25.4).toFixed(3)} in`, 'Nominal outside diameter');
  csv += row('Inner Diameter (ID)', `${results.dischargeIdMm.toFixed(2)} mm`, `${(results.dischargeIdMm / 25.4).toFixed(3)} in`, 'Flow bore area');
  csv += row('Wall Thickness (t)', `${dischargeWallMm.toFixed(2)} mm`, `${(dischargeWallMm / 25.4).toFixed(3)} in`, 'Minimum nominal wall');
  csv += row(
    'Flow Velocity',
    `${results.dischargeVelocityMps.toFixed(2)} m/s`,
    `${(results.dischargeVelocityMps * 3.28084).toFixed(2)} ft/s`,
    'Discharge limit: 1.8 - 2.4 m/s (Electrostatic safe threshold)'
  );
  csv += row(
    'Velocity Head (v²/2g)',
    `${(Math.pow(results.dischargeVelocityMps, 2) / 19.62).toFixed(3)} m`,
    `${((Math.pow(results.dischargeVelocityMps * 3.28084, 2)) / 64.348).toFixed(3)} ft`,
    ''
  );
  csv += row('Reynolds Number (Re)', Math.round(results.dischargeReynolds).toString(), Math.round(results.dischargeReynolds).toString(), `Flow Regime: ${results.dischargeRegime}`);
  csv += row('Darcy Friction Factor (f)', results.dischargeFrictionFactor.toFixed(5), results.dischargeFrictionFactor.toFixed(5), 'Colebrook-White Implicit Solution');
  csv += row('Major Pipe Friction Loss', `${results.dischargePipeHeadLossM.toFixed(3)} m`, `${(results.dischargePipeHeadLossM * 3.28084).toFixed(3)} ft`, 'Darcy-Weisbach head loss');
  csv += row('Minor Fittings Head Loss', `${results.dischargeFittingsHeadLossM.toFixed(3)} m`, `${(results.dischargeFittingsHeadLossM * 3.28084).toFixed(3)} ft`, 'Crane TP-410 ΣK·v²/2g');
  csv += row('Total Discharge Head Loss', `${results.dischargeTotalHeadLossM.toFixed(3)} m`, `${(results.dischargeTotalHeadLossM * 3.28084).toFixed(3)} ft`, `${results.dischargePressureDropKpa.toFixed(2)} kPa / ${(results.dischargePressureDropKpa * 0.145038).toFixed(2)} psi`);
  csv += row('Pipe MAWP at Design Temp', `${results.dischargeMawpBar.toFixed(1)} bar`, `${(results.dischargeMawpBar * 14.5038).toFixed(1)} psi`, 'ASME B31.3 Eq. 3a pressure containment');
  csv += row();

  // 6. Total Dynamic Head (TDH) Breakdown
  csv += row('=== TOTAL DYNAMIC HEAD (TDH) BREAKDOWN ===');
  csv += row('Head Component', 'Head Loss (m of Diesel)', 'Head Loss (ft)', 'Pressure Equiv (kPa)', 'Pressure Equiv (psi)', 'Percentage of TDH');
  const tdhM = Math.max(0.001, results.totalDynamicHeadM);
  csv += row(
    'Static Head (Net Elevation Change)',
    results.staticHeadM.toFixed(3),
    (results.staticHeadM * 3.28084).toFixed(3),
    ((results.staticHeadM * fluid.computedDensityKgM3 * 9.80665) / 1000).toFixed(2),
    (((results.staticHeadM * fluid.computedDensityKgM3 * 9.80665) / 1000) * 0.145038).toFixed(2),
    `${((results.staticHeadM / tdhM) * 100).toFixed(1)}%`
  );
  csv += row(
    'Total Major Friction Head Loss',
    results.totalFrictionHeadLossM.toFixed(3),
    (results.totalFrictionHeadLossM * 3.28084).toFixed(3),
    ((results.totalFrictionHeadLossM * fluid.computedDensityKgM3 * 9.80665) / 1000).toFixed(2),
    (((results.totalFrictionHeadLossM * fluid.computedDensityKgM3 * 9.80665) / 1000) * 0.145038).toFixed(2),
    `${((results.totalFrictionHeadLossM / tdhM) * 100).toFixed(1)}%`
  );
  csv += row(
    'Total Minor Fittings Loss (ΣK)',
    results.totalMinorHeadLossM.toFixed(3),
    (results.totalMinorHeadLossM * 3.28084).toFixed(3),
    ((results.totalMinorHeadLossM * fluid.computedDensityKgM3 * 9.80665) / 1000).toFixed(2),
    (((results.totalMinorHeadLossM * fluid.computedDensityKgM3 * 9.80665) / 1000) * 0.145038).toFixed(2),
    `${((results.totalMinorHeadLossM / tdhM) * 100).toFixed(1)}%`
  );
  csv += row(
    'Terminal Delivery Pressure Req.',
    results.terminalPressureHeadM.toFixed(3),
    (results.terminalPressureHeadM * 3.28084).toFixed(3),
    ((results.terminalPressureHeadM * fluid.computedDensityKgM3 * 9.80665) / 1000).toFixed(2),
    (((results.terminalPressureHeadM * fluid.computedDensityKgM3 * 9.80665) / 1000) * 0.145038).toFixed(2),
    `${((results.terminalPressureHeadM / tdhM) * 100).toFixed(1)}%`
  );
  csv += row(
    'TOTAL DYNAMIC HEAD (TDH)',
    results.totalDynamicHeadM.toFixed(3),
    (results.totalDynamicHeadM * 3.28084).toFixed(3),
    results.totalDynamicHeadKPa.toFixed(2),
    results.totalDynamicHeadPsi.toFixed(2),
    '100.0%'
  );
  csv += row();

  // 7. NPSH Cavitation Margin Audit
  csv += row('=== NET POSITIVE SUCTION HEAD (NPSH) AUDIT ===');
  csv += row('Parameter', 'SI Metric (m diesel)', 'Imperial Unit (ft diesel)', 'Assessment Criteria');
  csv += row(
    'Atmospheric Head (P_atm / ρg)',
    ((results.atmosphericPressureKPa * 1000) / (fluid.computedDensityKgM3 * 9.80665)).toFixed(3),
    (((results.atmosphericPressureKPa * 1000) / (fluid.computedDensityKgM3 * 9.80665)) * 3.28084).toFixed(3),
    'Standard atmospheric sea level barometric pressure'
  );
  csv += row(
    'Suction Friction & Minor Loss (h_fs)',
    results.suctionTotalHeadLossM.toFixed(3),
    (results.suctionTotalHeadLossM * 3.28084).toFixed(3),
    'Total line pressure drop on suction intake'
  );
  csv += row(
    'Diesel Fuel Vapor Pressure Head (P_vp / ρg)',
    ((fluid.vaporPressureKPa * 1000) / (fluid.computedDensityKgM3 * 9.80665)).toFixed(3),
    (((fluid.vaporPressureKPa * 1000) / (fluid.computedDensityKgM3 * 9.80665)) * 3.28084).toFixed(3),
    'Fuel boiling threshold at operating temperature'
  );
  csv += row(
    'Net Positive Suction Head Available (NPSHa)',
    results.npshaM.toFixed(3),
    (results.npshaM * 3.28084).toFixed(3),
    'Available system suction energy at pump impeller eye'
  );
  csv += row(
    'Pump Required NPSH (NPSHr)',
    results.npshrM.toFixed(3),
    (results.npshrM * 3.28084).toFixed(3),
    'Manufacturer certified 3% head drop cavitation datum'
  );
  csv += row(
    'NPSH Safety Margin (NPSHa - NPSHr)',
    results.npshMarginM.toFixed(3),
    (results.npshMarginM * 3.28084).toFixed(3),
    'Hydraulic Institute HI 9.6.1 standard: ≥ 0.8 - 1.0 m'
  );
  csv += row('NPSH Cavitation Compliance Status', results.npshStatus, results.npshStatus, results.npshStatus === 'PASS' ? 'Compliant with HI 9.6.1 & ASME B31.3' : 'Risk of cavitation damage / vapor lock');
  csv += row();

  // 8. Pump Sizing, Operating Point & Electric Driver
  csv += row('=== PUMP SELECTION & OPERATING POINT MATCHING ===');
  csv += row('Parameter', 'Design Operating Point', 'Pump Rating / Curve Specification');
  csv += row('Selected Pump Model', `${pump.manufacturer} - ${pump.model}`, pump.type);
  csv += row('Rated Operating Speed', `${pump.speedRpm} RPM`, `Max Casing Working Pressure: ${pump.maxPressureBar} bar (${(pump.maxPressureBar * 14.5038).toFixed(1)} psi)`);
  if (results.pumpOperatingPoint) {
    csv += row(
      'Actual Operating Flow Rate',
      `${results.pumpOperatingPoint.flowM3h.toFixed(2)} m³/h`,
      `${results.pumpOperatingPoint.flowGpm.toFixed(1)} US GPM (System Curve Intersection)`
    );
    csv += row(
      'Actual Pump Developed Head',
      `${results.pumpOperatingPoint.headM.toFixed(2)} m diesel`,
      `${results.pumpOperatingPoint.headFt.toFixed(1)} ft diesel (Design TDH Demand: ${results.totalDynamicHeadM.toFixed(2)} m)`
    );
    csv += row('Pump Hydraulic Efficiency', `${results.pumpOperatingPoint.efficiencyPct.toFixed(1)}%`, 'At operating intersection point');
    csv += row('System Demand Satisfaction', results.pumpOperatingPoint.meetsDemand ? 'SATISFIED (Meets Flow & Head Demand)' : 'DEFICIENT (Head or Flow Insufficient)', '');
  } else {
    csv += row('Operating Flow Demand', `${results.flowRateM3h.toFixed(2)} m³/h`, `${(results.flowRateM3h * 4.40287).toFixed(1)} US GPM`);
    csv += row('Total Dynamic Head Demand', `${results.totalDynamicHeadM.toFixed(2)} m diesel`, `${(results.totalDynamicHeadM * 3.28084).toFixed(1)} ft diesel`);
  }
  csv += row('Hydraulic Power Output (Water Power)', `${results.hydraulicPowerKw.toFixed(3)} kW`, `${(results.hydraulicPowerKw * 1.34102).toFixed(3)} hp`);
  csv += row('Pump Shaft Brake Horsepower (BHP)', `${results.brakeHorsepowerKw.toFixed(2)} kW`, `${results.brakeHorsepowerHp.toFixed(2)} BHP`);
  csv += row(
    'Recommended Standard Electric Motor Driver',
    `${results.recommendedMotorKw.toFixed(2)} kW`,
    `${results.recommendedMotorHp.toFixed(2)} HP (Includes NEMA / API service margin factor)`
  );
  csv += row();

  // 9. Fittings & Minor Loss Bill of Materials (BOM)
  csv += row('=== PIPING FITTINGS & VALVES BILL OF MATERIALS (BOM) ===');
  csv += row('Line Section', 'Component Description', 'Loss Coeff K (per unit)', 'Quantity', 'Subtotal K', 'Minor Loss Contribution (m)', 'Minor Loss Contribution (ft)');
  if (fittings.length > 0) {
    const vS = results.suctionVelocityMps;
    const vD = results.dischargeVelocityMps;
    const g = 9.80665;
    const vHeadS = (vS * vS) / (2 * g);
    const vHeadD = (vD * vD) / (2 * g);

    fittings.forEach((fit) => {
      const subK = fit.kValue * fit.count;
      const vHead = fit.location === 'suction' ? vHeadS : vHeadD;
      const lossM = subK * vHead;
      csv += row(
        fit.location.toUpperCase(),
        fit.name,
        fit.kValue.toFixed(2),
        fit.count,
        subK.toFixed(2),
        lossM.toFixed(3),
        (lossM * 3.28084).toFixed(3)
      );
    });
  } else {
    csv += row('No specialized fittings configured in current model');
  }
  csv += row();

  // 10. ASME B31.3 Compliance & Engineering Audit Findings
  csv += row('=== ASME B31.3 CODE COMPLIANCE AUDIT FINDINGS ===');
  csv += row('Overall Compliance Status', results.asmeCompliance.status);
  csv += row('Suction Velocity Check', results.asmeCompliance.suctionVelocityValid ? 'PASS (<= 1.2 m/s)' : 'NON-COMPLIANT (Excessive Velocity / Friction Risk)');
  csv += row('Discharge Velocity Check', results.asmeCompliance.dischargeVelocityValid ? 'PASS (<= 2.4 m/s)' : 'NON-COMPLIANT (Exceeds API RP 2003 Electrostatic Safe Limit)');
  csv += row('Pressure Containment Check', results.asmeCompliance.pressureValid ? 'PASS (Within Material MAWP Rating)' : 'NON-COMPLIANT (Overpressure Risk)');
  csv += row('NPSH Cavitation Margin Check', results.asmeCompliance.npshValid ? 'PASS (Margin >= 1.0 m)' : 'WARNING / FAIL (Cavitation Risk)');
  csv += row();
  csv += row('Code Verification Messages:');
  csv += row('Type', 'Code Ref', 'Engineering Verification Message');
  results.asmeCompliance.messages.forEach((msg) => {
    csv += row(msg.type.toUpperCase(), msg.code, msg.message);
  });

  return csv;
}

export function exportHydraulicResultsCsv(params: CsvExportParams): void {
  const csvContent = generateHydraulicCsvString(params);
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');

  const safeProj = (params.project.projectNumber || 'DIESEL_SIZING')
    .replace(/[^a-zA-Z0-9_-]/g, '_');
  const safeDate = (params.project.date || new Date().toISOString().split('T')[0])
    .replace(/[^0-9-]/g, '');

  link.setAttribute('href', url);
  link.setAttribute('download', `${safeProj}_ASME_B31_3_Hydraulic_Results_${safeDate}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
